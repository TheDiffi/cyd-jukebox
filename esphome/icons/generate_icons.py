"""Render the UI icons as pixel-exact PNGs.

Most icons are drawn as ASCII grids below. The large play icon and the back
arrow are Pictogrammers' Memory icons (Apache 2.0), drawn on a 22x22 grid.
Rendering those through a font or an SVG rasteriser at 2x lands their edges on
half pixels, which blurs them. Memory paths only use horizontal and vertical
lines on whole grid units, so this script fills them on the 22x22 grid itself.
Every grid cell is scaled up to an exact block of screen pixels.

Run it from anywhere; it writes next to itself:

    python3 esphome/icons/generate_icons.py

Needs Pillow and internet access (to fetch the Memory SVGs).
"""

