def _memory_path(name):
    with urllib.request.urlopen(MEMORY_URL.format(name)) as resp:
        svg = resp.read().decode()
    return re.search(r' d="([^"]+)"', svg).group(1)


def _fill(path):
    """Even-odd fill of an M/L/H/V/Z path, sampled at the centre of each grid cell."""
    polygons, current = [], []
    x = y = 0.0
    for cmd, args in re.findall(r"([MLHVZ])([^MLHVZ]*)", path):
        nums = [float(n) for n in re.findall(r"-?\d+\.?\d*", args)]
        if cmd == "M":
            if current:
                polygons.append(current)
            current = []
            for i in range(0, len(nums), 2):
                x, y = nums[i], nums[i + 1]
                current.append((x, y))
        elif cmd == "L":
            for i in range(0, len(nums), 2):
                x, y = nums[i], nums[i + 1]
                current.append((x, y))
        elif cmd == "H":
            for n in nums:
                x = n
                current.append((x, y))
        elif cmd == "V":
            for n in nums:
                y = n
                current.append((x, y))
        elif cmd == "Z" and current:
            polygons.append(current)
            current = []
    if current:
        polygons.append(current)

    grid = [[0] * GRID for _ in range(GRID)]
    for py in range(GRID):
        for px in range(GRID):
            cx, cy = px + 0.5, py + 0.5
            inside = False
            for poly in polygons:
                for (x1, y1), (x2, y2) in zip(poly, poly[1:] + poly[:1]):
                    if (y1 > cy) != (y2 > cy) and cx < x1 + (cy - y1) * (x2 - x1) / (y2 - y1):
                        inside = not inside
            grid[py][px] = int(inside)
    return grid


def _ascii(name):
    return [[int(c == "#") for c in line.strip()] for line in ASCII[name].strip().splitlines()]


def _save(grid, scale, path):
    # Black shape on transparent: ESPHome turns this into a 1-bit alpha mask for LVGL
    height, width = len(grid), len(grid[0])
    img = Image.new("RGBA", (width * scale, height * scale), (0, 0, 0, 0))
    for y in range(height):
        for x in range(width):
            if grid[y][x]:
                img.paste((0, 0, 0, 255), (x * scale, y * scale, (x + 1) * scale, (y + 1) * scale))
    img.save(path)


def main():
    for out_name, (source, scale) in ICONS.items():
        if source.startswith("ascii:"):
            grid = _ascii(source.removeprefix("ascii:"))
        else:
            grid = _fill(_memory_path(source))
        _save(grid, scale, OUT / f"{out_name}.png")
        print(f"{out_name}.png  {len(grid[0]) * scale}x{len(grid) * scale}")


if __name__ == "__main__":
    main()
